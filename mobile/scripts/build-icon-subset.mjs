#!/usr/bin/env node
/**
 * The app's own Phosphor subset (M5.12a, 09 §12, ADR-473 "an own icon subset"): src/ui/icons/phosphorSubset.tsx holds the icons that
 * src/ui/icons/Icon.tsx names, each with the two weights the app draws (`regular`, `fill`; IconWeight in Icon.tsx). Phosphor's own
 * icon files carry all six weights (thin, light, regular, bold, fill, duotone), so two thirds of their paths were bundled for nothing.
 *
 *   node scripts/build-icon-subset.mjs           writes the file
 *   node scripts/build-icon-subset.mjs --check   exit 1 when the file is not what this script would write (tests run it too)
 *
 * The icon list is read from Icon.tsx: one `import { XIcon } from './phosphorSubset'` name per icon. Adding an icon: add its name to
 * that import and to the map, then run this script. Paths come unchanged from phosphor-react-native's generated defs.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const iconFile = join(root, 'src', 'ui', 'icons', 'Icon.tsx');
const outFile = join(root, 'src', 'ui', 'icons', 'phosphorSubset.tsx');
const phosphor = join(root, 'node_modules', 'phosphor-react-native');
const WEIGHTS = ['regular', 'fill'];

/** The icon names Icon.tsx imports from the subset, in their order there. */
export function subsetNames(source) {
  const match = /import\s*\{([^}]*)\}\s*from\s*'\.\/phosphorSubset';/.exec(source);
  if (!match) throw new Error("Icon.tsx has no `import { … } from './phosphorSubset'`");
  return match[1]
    .split(',')
    .map((name) => name.trim())
    .filter(Boolean);
}

/** The JSX of one weight in a Phosphor defs file: the fragment after `['<weight>',`. */
function weightJsx(defs, weight, file) {
  const match = new RegExp(`\\[\\s*'${weight}',\\s*(<>[\\s\\S]*?</>),\\s*\\]`).exec(defs);
  if (!match) throw new Error(`${file}: no '${weight}' weight`);
  return match[1].replace(/\s+/g, ' ').replace(/>\s+</g, '><').trim();
}

export function buildSubset() {
  const names = subsetNames(readFileSync(iconFile, 'utf8'));
  const version = JSON.parse(readFileSync(join(phosphor, 'package.json'), 'utf8')).version;
  const elements = new Set();
  const blocks = names.map((exportName) => {
    if (!exportName.endsWith('Icon')) throw new Error(`${exportName}: subset names end in "Icon", as Phosphor's exports do`);
    const base = exportName.slice(0, -'Icon'.length);
    const iconSource = readFileSync(join(phosphor, 'src', 'icons', `${base}.tsx`), 'utf8');
    const kebab = /name="([^"]+)"/.exec(iconSource)?.[1];
    if (!kebab) throw new Error(`${base}.tsx: no name="…"`);
    const defsFile = join(phosphor, 'src', 'defs', `${base}.tsx`);
    const defs = readFileSync(defsFile, 'utf8');
    const weights = WEIGHTS.map((weight) => {
      const jsx = weightJsx(defs, weight, `defs/${base}.tsx`);
      for (const tag of jsx.matchAll(/<([A-Z][A-Za-z]*)/g)) elements.add(tag[1]);
      return `  ['${weight}', ${jsx}],`;
    });
    const constName = `${base.charAt(0).toLowerCase()}${base.slice(1)}Weights`;
    return [
      `const ${constName} = new Map<GlyphWeight, ReactElement>([`,
      ...weights,
      ']);',
      `export const ${exportName}: Glyph = (props: GlyphProps) => <PhosphorGlyph {...props} weights={${constName}} name="${kebab}" />;`,
    ].join('\n');
  });
  const svgImports = [...elements].sort().join(', ');
  return [
    `/* GENERATED by scripts/build-icon-subset.mjs from phosphor-react-native ${version}: do not edit. The icons src/ui/icons/Icon.tsx`,
    ` * names, with the two weights the app draws (regular, fill), so the web bundle no longer carries the other four (M5.12a, 09 §12). */`,
    "import type { ReactElement } from 'react';",
    `import { ${svgImports} } from 'react-native-svg';`,
    '',
    "import { PhosphorGlyph, type Glyph, type GlyphProps, type GlyphWeight } from './PhosphorGlyph';",
    '',
    blocks.join('\n\n'),
    '',
  ].join('\n');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const next = buildSubset();
  if (process.argv.includes('--check')) {
    const current = readFileSync(outFile, 'utf8');
    if (current !== next) {
      console.error('✖ src/ui/icons/phosphorSubset.tsx is out of date: run node scripts/build-icon-subset.mjs');
      process.exit(1);
    }
    console.log('✔ icon subset up to date');
  } else {
    writeFileSync(outFile, next);
    console.log(`✔ wrote ${outFile}`);
  }
}
