// Builds what the public Blade pages need from sources that must not ship: run from web/ with `node scripts/build-public-assets.mjs`.
// Output is committed, because the host has no Node (05_ARCHITECTURE section 19).
//   resources/views/components/icons/phosphor-sprite.blade.php   the Phosphor glyphs the pages use, as one sprite
//   public/brand/photos/<key>-<width>.webp                       night photos of the landing page: re-encoded, no metadata
//   resources/data/brand-photos.php                              their sizes, focal points, alt texts and placeholders
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const web = join(dirname(fileURLToPath(import.meta.url)), '..');
const seed = join(web, '..', 'design', 'seed-photos');

const GLYPHS = [
  'arrow-right',
  'arrow-square-out',
  'bookmark-simple',
  'calendar-blank',
  'caret-right',
  'clock',
  'compass',
  'device-mobile',
  'images',
  'list-bullets',
  'lock-simple',
  'magnifying-glass',
  'map-pin',
  'prohibit',
  'qr-code',
  'share-network',
  'wrench',
];

const PHOTOS = [
  { key: 'landing-hero', file: 'generic-exterior-01.jpg' },
  { key: 'landing-station', file: 'generic-exterior-03.jpg' },
  { key: 'state-garage', file: 'generic-exterior-04.jpg' },
  { key: 'landing-taillight', file: 'generic-detail-01.jpg' },
  { key: 'landing-wheel', file: 'generic-wheels-03.jpg' },
];

// 828 on top of the media pipeline's four: a phone at 2x gets a hero that fits instead of the next size up, which is what the LCP budget hangs on.
const WIDTHS = [320, 640, 828, 1080, 1600];
const QUALITY = 66;

function sprite() {
  const symbols = GLYPHS.map((name) => {
    const svg = readFileSync(join(web, 'node_modules/@phosphor-icons/core/assets/regular', `${name}.svg`), 'utf8');
    const inner = /<svg[^>]*>(.*)<\/svg>/s.exec(svg)?.[1];

    if (!inner) throw new Error(`Unexpected Phosphor file: ${name}`);

    return `  <symbol id="ph-${name}" viewBox="0 0 256 256" fill="currentColor">${inner.trim()}</symbol>`;
  }).join('\n');

  writeFileSync(
    join(web, 'resources/views/components/icons/phosphor-sprite.blade.php'),
    `{{-- AUTO-GENERATED by web/scripts/build-public-assets.mjs from @phosphor-icons/core. DO NOT EDIT BY HAND. --}}\n<svg xmlns="http://www.w3.org/2000/svg" width="0" height="0" aria-hidden="true" focusable="false" class="absolute">\n${symbols}\n</svg>\n`,
  );
}

const BACKSLASH = String.fromCharCode(92);
const PHP_QUOTE = String.fromCharCode(39);

function php(value, indent = 0) {
  const pad = '    '.repeat(indent);

  if (Array.isArray(value)) return `[\n${value.map((item) => `${pad}    ${php(item, indent + 1)},`).join('\n')}\n${pad}]`;
  if (value && typeof value === 'object') return `[\n${Object.entries(value).map(([key, item]) => `${pad}    '${key}' => ${php(item, indent + 1)},`).join('\n')}\n${pad}]`;
  if (typeof value === 'string') return PHP_QUOTE + value.replace(/[\\']/g, (char) => BACKSLASH + char) + PHP_QUOTE;

  return String(value);
}

async function photos() {
  const manifest = JSON.parse(readFileSync(join(seed, 'manifest.json'), 'utf8'));
  const list = Array.isArray(manifest) ? manifest : manifest.photos;
  const out = join(web, 'public/brand/photos');
  mkdirSync(out, { recursive: true });
  const data = {};

  for (const { key, file } of PHOTOS) {
    const entry = list.find((item) => item.file === file);

    if (!entry) throw new Error(`${file} is not in the manifest`);

    const source = sharp(join(seed, file)).rotate();
    const { width, height } = await source.metadata();
    const steps = [...WIDTHS.filter((step) => step < width), Math.min(width, WIDTHS.at(-1))];
    const variants = [];

    for (const step of steps) {
      const name = `${key}-${step}.webp`;
      const info = await source.clone().resize({ width: step }).webp({ quality: QUALITY, effort: 6 }).toFile(join(out, name));
      variants.push({ width: info.width, height: info.height, path: `/brand/photos/${name}` });
    }

    const tiny = await source.clone().resize({ width: 16 }).webp({ quality: 30 }).toBuffer();

    data[key] = {
      id: key,
      width,
      height,
      focal_x: entry.focal?.x ?? 0.5,
      focal_y: entry.focal?.y ?? 0.5,
      alt: { de: entry.alt_de, en: entry.alt_en },
      placeholder: `data:image/webp;base64,${tiny.toString('base64')}`,
      variants,
    };
  }

  writeFileSync(
    join(web, 'resources/data/brand-photos.php'),
    `<?php\n\n// AUTO-GENERATED by web/scripts/build-public-assets.mjs. DO NOT EDIT BY HAND.\n\nreturn ${php(data)};\n`,
  );
}

sprite();
await photos();
