// Route registry of the visual matrix. Every module adds its routes here (see tests/e2e/README.md).
//
// Fields
//   id        route ID from docs/04_SCREEN_REGISTER.md
//   path      URL path. Dynamic segments use the deterministic DemoSeeder values; ids that change with every seed are
//             `{r34}`, `{r34Photo}`, `{r34Mod}`, `{r34Update}`, `{draft}`, `{s15}`, `{decision}`, read per run (support/garage.mjs demoIds); admin: `{auditEvent}` (support/path-tokens.mjs).
//   phase     1 | 2 | 3: the phase that shipped the route; `--tier=phase --phase=N` takes every route of phases 1..N
//   auth      'guest' | 'member' (lukas.sc) | 'member-empty' (nina.neu) | 'member-blocker' (paul.roadster, who has blocked
//             nina.neu) | 'member-kenji' (kenji.r34) | 'member-affected' (tobi.quattro) | 'member-reporter' (nico.sti) |
//             'member-sessions' (the SET-06 fixture, DQ-453) |
//             'member-username' | 'member-profile' (onboarding fixtures), see support/auth.mjs; admin: 'staff-guest' (signed out),
//             'staff-owner' | 'staff-admin' | 'staff-moderator' | 'staff-support' | 'staff-content' | 'staff-analyst' (one fixture per role),
//             'staff-challenge' (password accepted, code pending: ADM-02), 'staff-enrol' (signed in, TOTP not enrolled: ADM-03), support/staff.mjs.
//   states    states the route ships; `default` is mandatory
//   ready     selector of an element that proves the right screen rendered, so that an SPA
//             fallback or a +not-found page can never pass as a screenshot of this route
//   notes     free text for design QA
// Optional
//   viewports widths to restrict this route to, e.g. [1280, 1440]. Needs a reason in `notes`.
//   capture   'viewport' | 'page' (document scroll) | 'expanded' (grow the viewport to the inner
//             scroller). Default: 'viewport' for the SPA, 'page' for public and admin pages.
//   maxHeight with capture 'expanded': the picture's height at most, in CSS px (1000–12000), so an endless list (HOME-01's
//             stream) gives a picture of a fixed bound. The content is measured once, before the viewport grows.
//   status    'planned' = not built yet: not selected by default and listed in the output.
//             Naming it in --routes runs it, and it fails honestly until it exists.
//   expectStatus HTTP status the page answers by design, such as 410 for a revoked QR code. Without it, 400 and up fail.
//   hostDependent true = the picture shows the server's host (a QR code of APP_URL: GAR-04, QR-02, QR-04, WEB-03, WEB-04,
//             VEH-07; the host in WEB-09's URL help). Its baseline is compared and written only when the run is on SPEEDCLUB_BASELINE_URL (default
//             http://localhost:8080); a run elsewhere (the isolated :8081 copy) still audits it and reports baseline `host`.
//   volatile  true = ADR-223: the picture is the platform's live activity (ADM-06, ADM-08, ADM-44): DOM audit, axe and design review as
//             usual, no baseline comparison or update outside the fixture states loading/error/empty (baseline `volatile`).
//   qaContract false = the page does not report its qa* overrides yet (see README). Default true.
//             Only the Phase 1 skeleton may use false; M1.1 removes it.

